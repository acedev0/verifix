"""Data types and models for the VeriFix framework."""

from __future__ import annotations

from dataclasses import dataclass, field
from enum import Enum
from typing import Any, Dict, List, Optional


class VerificationStatus(str, Enum):
    """Result status of formal verification."""
    VERIFIED = "VERIFIED"  # Mathematically proven sound (negation of spec is UNSAT)
    COUNTEREXAMPLE_FOUND = "COUNTEREXAMPLE_FOUND"  # Bug found: concrete model found (SAT)
    UNKNOWN = "UNKNOWN"  # Solver timed out or non-linear/undecidable theory
    SYNTAX_ERROR = "SYNTAX_ERROR"  # Candidate code could not be parsed
    RUNTIME_ERROR = "RUNTIME_ERROR"  # Error occurred during translation or execution


@dataclass
class Counterexample:
    """A concrete input assignment demonstrating a bug or specification violation."""
    inputs: Dict[str, Any]
    violation_type: str  # e.g., "DIVISION_BY_ZERO", "POSTCONDITION_VIOLATION", "INDEX_OUT_OF_BOUNDS"
    description: str
    failed_condition: Optional[str] = None
    line_number: Optional[int] = None
    trace: List[str] = field(default_factory=list)

    def format_feedback(self) -> str:
        """Format the counterexample into structured feedback for LLM prompt."""
        formatted_inputs = ", ".join(f"{k} = {v}" for k, v in self.inputs.items())
        lines = [
            f"- Counterexample inputs: {formatted_inputs}",
            f"- Violation: {self.violation_type}",
            f"- Description: {self.description}",
        ]
        if self.failed_condition:
            lines.append(f"- Violated Condition: {self.failed_condition}")
        if self.line_number:
            lines.append(f"- Location: line {self.line_number}")
        if self.trace:
            lines.append("- Path Condition / Trace:")
            for step in self.trace:
                lines.append(f"    * {step}")
        return "\n".join(lines)


@dataclass
class Specification:
    """Formal specifications, contracts, and safety invariants for a function."""
    preconditions: List[str] = field(default_factory=list)
    postconditions: List[str] = field(default_factory=list)
    invariants: List[str] = field(default_factory=list)
    safety_checks: List[str] = field(default_factory=lambda: [
        "no_division_by_zero",
        "no_index_out_of_bounds",
        "no_none_dereference"
    ])
    param_types: Dict[str, str] = field(default_factory=dict)
    return_type: Optional[str] = None

    def add_precondition(self, expr: str) -> Specification:
        self.preconditions.append(expr)
        return self

    def add_postcondition(self, expr: str) -> Specification:
        self.postconditions.append(expr)
        return self

    def add_invariant(self, expr: str) -> Specification:
        self.invariants.append(expr)
        return self

    def enable_safety_check(self, rule: str) -> Specification:
        if rule not in self.safety_checks:
            self.safety_checks.append(rule)
        return self

    def disable_safety_check(self, rule: str) -> Specification:
        if rule in self.safety_checks:
            self.safety_checks.remove(rule)
        return self


@dataclass
class VerificationResult:
    """Outcome of verifying a function against a specification."""
    status: VerificationStatus
    counterexample: Optional[Counterexample] = None
    details: str = ""
    proof_summary: Optional[str] = None
    solver_time_ms: float = 0.0

    @property
    def is_verified(self) -> bool:
        return self.status == VerificationStatus.VERIFIED


@dataclass
class PatchCandidate:
    """A patch proposal generated by the LLM or synthesis engine."""
    iteration: int
    code: str
    explanation: str = ""
    verification_result: Optional[VerificationResult] = None


@dataclass
class RepairResult:
    """The complete result of the VeriFix neurosymbolic repair loop."""
    original_code: str
    function_name: str
    success: bool
    verified_patch: Optional[str]
    iterations: int
    history: List[PatchCandidate] = field(default_factory=list)
    initial_counterexample: Optional[Counterexample] = None
    total_time_ms: float = 0.0
